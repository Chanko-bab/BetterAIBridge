# Build BetterAIBridge self-extracting installer with IExpress.
# ASCII only. Usage: powershell -ExecutionPolicy Bypass -File packaging\build.ps1 [-Version 0.4.59]
param(
    [string]$Version = '',
    [string]$Src = '',
    [string]$Out = '',
    [switch]$SkipCheck
)
$ErrorActionPreference = 'Stop'
$Pkg = $PSScriptRoot
if (-not $Src) { $Src = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path }
if (-not $Out) { $Out = Join-Path (Split-Path $Src -Parent) 'dist' }
if (-not $Version) {
    $vf = Join-Path $Src 'VERSION.txt'
    if (Test-Path $vf) {
        $Version = ((Get-Content $vf -Raw) -replace '^\s*BetterAIBridge\s*', '').Trim()
    }
    if (-not $Version) { throw 'Version not specified and VERSION.txt missing' }
}
# Keep installer UI/paths and install.json version in sync with this build.
[System.IO.File]::WriteAllText((Join-Path $Pkg 'version.txt'), $Version, (New-Object System.Text.ASCIIEncoding))
$Stage = Join-Path $Pkg 'payload'
$Zip = Join-Path $Pkg 'payload.zip'
$Sed = Join-Path $Pkg 'bab.sed'
$ExeOut = Join-Path $Out ("BetterAIBridge-Setup-$Version.exe")

function Step($m) { Write-Host "[build] $m" }

# ---- 0. self-check (fail fast, do not ship a broken payload) -----------
if ($SkipCheck) {
    Step "self-check skipped (-SkipCheck)"
} else {
    $CheckScript = Join-Path $Src 'tools\check.py'
    $CheckPy = Join-Path $Src '.venv\Scripts\python.exe'
    if (-not (Test-Path $CheckScript)) {
        Step "no tools/check.py in $Src, skipping self-check"
    } elseif (-not (Test-Path $CheckPy)) {
        Step "no .venv in $Src, skipping self-check"
    } else {
        Step "running tools/check.py (this takes about a minute)"
        & $CheckPy $CheckScript
        if ($LASTEXITCODE -ne 0) {
            Step "self-check FAILED (exit $LASTEXITCODE) - not building"
            exit 1
        }
        Step "self-check passed"
    }
}

# ---- 1. stage payload -------------------------------------------------
Step "staging payload from $Src"
if (Test-Path $Stage) { Remove-Item -Recurse -Force $Stage }
New-Item -ItemType Directory -Path $Stage | Out-Null

$SkipDirs = @('.venv', '__pycache__', 'logs', 'runtime', '.git', '.github', 'docs', 'payload', 'tmp', '_src', 'local_tts', '_moss_src', 'packaging')
$SkipNames = @('sessions.json', 'state.json', 'flybrain_state.json', 'qrcode.png', 'brain_state.json', 'stomach.json.real', 'flybrain_core.v1.py', '_render_check.txt', '_moss_src.zip', 'core_token')

# 用户数据/本机运行态，绝不进安装包
$Private = @(
    'WiseEntity\entity\config\sense.json',
    'WiseEntity\entity\config\face.png',
    'WiseEntity\entity\config\emotion_profile.json',
    'WiseEntity\entity\emotion\state.json',
    'WiseEntity\entity\brain\flybrain_state.json',
    'WiseEntity\entity\state\core_token',
    'config\sense.json'
)
$count = 0
Get-ChildItem -Path $Src -Recurse -File -Force | ForEach-Object {
    $rel = $_.FullName.Substring($Src.Length).TrimStart('\')
    if ($Private -contains $rel) { return }
    if ($rel -like 'WiseEntity\entity\self\*') { return }
    $parts = $rel.Split('\')
    if ($parts | Where-Object { $SkipDirs -contains $_ }) { return }
    if ($_.Name -match '\.(pyc|pyo)$') { return }
    if ($SkipNames -contains $_.Name) { return }
    if ($_.Name -like 'preview_*') { return }
    if ($_.Name -like '*.jsonl') { return }
    if ($_.Name -like '*.bak*') { return }
    if ($rel -eq 'config\app.yaml') { return }   # generated by installer from template
    if ($rel -eq 'config\sense.json') { return } # runtime: port/token written by launcher
    # 模组包随安装包走：只带 program_cache 顶层的 .pbab，_modsrc 之类的源码不进包
    if ($rel -match '^program_cache\\') {
        if ($rel -notmatch '^program_cache\\[^\\]+\.pbab$') { return }
    }
    if ($rel -like 'program_bundle\program_*') { return }
    if ($rel -like 'program_bundle\plugins*') { return }   # installed modules stay out
    if ($rel -like 'tools\_*') { return }          # internal patch scripts stay out
    if ($rel -like 'templates\*') { return }       # module scaffold is dev-only
    if ($rel -eq 'tools\new_module.py') { return } # ditto
    if ($_.Name -like '*.joybak*') { return }
    $dest = Join-Path $Stage $rel
    New-Item -ItemType Directory -Force -Path (Split-Path $dest) | Out-Null
    Copy-Item $_.FullName $dest -Force
    $script:count++
}
Step "copied $count files"

# clean per-user state so every install starts fresh
foreach ($d in @('WiseEntity\entity\memory', 'WiseEntity\entity\state')) {
    $p = Join-Path $Stage $d
    if (Test-Path $p) { Get-ChildItem $p -Force | Remove-Item -Recurse -Force -ErrorAction SilentlyContinue }
}

# never ship the author's own key / persona / runtime state
$Personal = @(
    'config\install.json',
    'WiseEntity\entity\config\llm.json',
    'WiseEntity\entity\persona\persona.md',
    'WiseEntity\entity\persona\drift.json',
    'WiseEntity\entity\registry\programs.local.json',
    'WiseEntity\entity\config\emotion_profile.json'
)
$scrubbed = 0
foreach ($rel in $Personal) {
    $p = Join-Path $Stage $rel
    if (Test-Path $p) { Remove-Item $p -Force; $scrubbed++ }
}
Step "scrubbed $scrubbed personal file(s)"

# placeholders: no key, persona still PLACEHOLDER -> first run must show the wizard
# placeholders: copy UTF-8 templates from staged tree so Chinese stays readable
$llmTplSrc = Join-Path $Stage "WiseEntity\entity\config\llm.placeholder.json"
$llmPath = Join-Path $Stage "WiseEntity\entity\config\llm.json"
if (-not (Test-Path $llmTplSrc)) { throw "llm.placeholder.json missing in payload" }
Copy-Item -LiteralPath $llmTplSrc -Destination $llmPath -Force

$personaTplSrc = Join-Path $Stage "WiseEntity\entity\persona\persona.placeholder.md"
$personaPath = Join-Path $Stage "WiseEntity\entity\persona\persona.md"
if (-not (Test-Path $personaTplSrc)) { throw "persona.placeholder.md missing in payload" }
Copy-Item -LiteralPath $personaTplSrc -Destination $personaPath -Force
foreach ($tpl in @($llmTplSrc, $personaTplSrc)) { Remove-Item -LiteralPath $tpl -Force -ErrorAction SilentlyContinue }
Step "wrote placeholder llm.json + persona.md"
# no module installed on a fresh machine; absolute dirs must not leak from the author's tree
$reg = Join-Path $Stage 'program_bundle\registry.json'
New-Item -ItemType Directory -Force -Path (Split-Path $reg) | Out-Null
[System.IO.File]::WriteAllText($reg, '{"format":"bab-registry/1","updated":"","modules":{}}', (New-Object System.Text.UTF8Encoding($false)))
Step 'wrote clean registry.json'

$verFile = Join-Path $Stage 'VERSION.txt'
[System.IO.File]::WriteAllText($verFile, "BetterAIBridge $Version" + [char]13 + [char]10, (New-Object System.Text.ASCIIEncoding))
if (-not (Test-Path (Join-Path $Stage 'config\app.yaml.template'))) { throw 'app.yaml.template missing in payload' }

# ---- 2. zip ----------------------------------------------------------
Step 'zipping payload'
if (Test-Path $Zip) { Remove-Item $Zip -Force }
Add-Type -AssemblyName System.IO.Compression.FileSystem
[System.IO.Compression.ZipFile]::CreateFromDirectory($Stage, $Zip, [System.IO.Compression.CompressionLevel]::Optimal, $false)
Step ("payload.zip = {0:N0} bytes" -f (Get-Item $Zip).Length)

# ---- 2b. icon for the installer window --------------------------------
$icoSrc = Join-Path $Src 'assets\bab.ico'
if (Test-Path $icoSrc) { Copy-Item $icoSrc (Join-Path $Pkg 'bab.ico') -Force; Step 'copied bab.ico' }
else { Step 'WARN bab.ico missing, installer keeps the default icon' }
$setupIcoSrc = Join-Path $Src 'assets\bab-setup.ico'
if (Test-Path $setupIcoSrc) { Copy-Item $setupIcoSrc (Join-Path $Pkg 'bab-setup.ico') -Force; Step 'copied bab-setup.ico' }
else { Step 'WARN bab-setup.ico missing, installer window keeps the default icon' }
$bgSrc = Join-Path $Src 'assets\bab-bg.jpg'
if (Test-Path $bgSrc) { Copy-Item $bgSrc (Join-Path $Pkg 'bab-bg.jpg') -Force; Step 'copied bab-bg.jpg' }
else { Step 'WARN bab-bg.jpg missing, installer/dialogs keep flat background' }

# ---- 3. SED + IExpress -----------------------------------------------
Step 'writing bab.sed'
$sedLines = @(
    '[Version]',
    'Class=IEXPRESS',
    'SEDVersion=3',
    '[Options]',
    'PackagePurpose=InstallApp',
    'ShowInstallProgramWindow=0',
    'HideExtractAnimation=1',
    'UseLongFileName=1',
    'InsideCompressed=0',
    'CAB_FixedSize=0',
    'CAB_ResvCodeSigning=0',
    'RebootMode=N',
    'InstallPrompt=',
    'DisplayLicense=',
    'FinishMessage=',
    "TargetName=$ExeOut",
    "FriendlyName=BetterAIBridge $Version Setup",
    'AppLaunched=wscript.exe install.vbs',
    'PostInstallCmd=<None>',
    'AdminQuietInstCmd=',
    'UserQuietInstCmd=',
    'SourceFiles=SourceFiles',
    '[Strings]',
    'FILE0="payload.zip"',
    'FILE1="install.ps1"',
    'FILE2="install.cmd"',
    'FILE3="install.vbs"',
    'FILE4="bab.ico"',
  'FILE5="bab-setup.ico"',
    'FILE6="bab-bg.jpg"',
    'FILE7="version.txt"',
    '[SourceFiles]',
    "SourceFiles0=$Pkg\",
    '[SourceFiles0]',
    '%FILE0%=',
    '%FILE1%=',
    '%FILE2%=',
    '%FILE3%=',
    '%FILE4%=',
  '%FILE5%=',
    '%FILE6%=',
    '%FILE7%='
)
[System.IO.File]::WriteAllLines($Sed, $sedLines, (New-Object System.Text.ASCIIEncoding))

if (-not (Test-Path $Out)) { New-Item -ItemType Directory -Force -Path $Out | Out-Null }
if (Test-Path $ExeOut) { Remove-Item $ExeOut -Force }
Step 'running iexpress'
$proc = Start-Process -FilePath (Join-Path $env:WINDIR 'system32\iexpress.exe') -ArgumentList '/N', '/Q', $Sed -Wait -PassThru
if ($proc.ExitCode -ne 0) { throw "iexpress failed with exit code $($proc.ExitCode)" }
if (-not (Test-Path $ExeOut)) { throw "installer not produced: $ExeOut" }

$h = (Get-FileHash $ExeOut -Algorithm SHA256).Hash.ToLower()
$sz = (Get-Item $ExeOut).Length
Step ("OK  {0}" -f $ExeOut)
Step ("    {0:N0} bytes  sha256 {1}" -f $sz, $h)
Step ("    payload {0:N0} bytes / {1} files" -f (Get-Item $Zip).Length, (Get-ChildItem $Stage -Recurse -File | Measure-Object).Count)
